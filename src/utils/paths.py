"""Single source of truth for every path the pipeline reads or writes.

Everything generated by a run lives under one `artifacts/` tree::

    artifacts/
      data/        data.csv, ground_truth.parquet   (the synthetic panel)
      logs/        execution.log
      models/      iforest.joblib, vae_best.pt, vae/, vae_tuning/
      tuning/      optuna_*.db, best_params_*.yaml  (Optuna outputs)
      reports/     anomaly_report.{html,md}, model_documentation.md, oot_top10_*.xlsx, figures/

so the repository root holds only source (``main.py``, ``src/``, ``tests/``,
``docs/``) and the entire generated state can be inspected -- or deleted -- in
one place.

Two properties every value here must keep:

* **Relative, never absolute.** ``tests/conftest.py`` chdirs the whole session
  into a throwaway sandbox precisely so these defaults resolve there and never
  touch the real tree. An absolute path would defeat that.
* **Built with :func:`os.path.join`,** so Windows and POSIX separators are both
  handled by the standard library rather than by string concatenation.

``figures/`` is deliberately flat: figure filenames already carry their
producing module as a prefix (``iforest_*``, ``vae_*``, ``embedding_*``,
``roc_pr_*``), which is enough to group them without a directory per module.
This still satisfies the project-wide rule that *every* figure from *every*
module lands under one figures directory.
"""

