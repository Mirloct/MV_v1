# safe to delete once a study has finished (see .gitignore).
VAE_TUNING_CHECKPOINT_DIR = os.path.join(MODELS_DIR, "vae_tuning")

# -- tuning artifacts ------------------------------------------------------- #
IFOREST_STUDY_DB = os.path.join(TUNING_DIR, "optuna_iforest.db")
