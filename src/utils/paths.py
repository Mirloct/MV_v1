TUNING_DIR = os.path.join(ARTIFACTS_DIR, "tuning")
REPORTS_DIR = os.path.join(ARTIFACTS_DIR, "reports")
FIGURES_DIR = os.path.join(REPORTS_DIR, "figures")

# -- data ------------------------------------------------------------------- #
DATA_PATH = os.path.join(DATA_DIR, "data.csv")
